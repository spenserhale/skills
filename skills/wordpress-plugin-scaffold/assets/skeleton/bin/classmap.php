<?php
/**
 * Regenerate src/classmap.php from the classes declared under src/.
 *
 * Usage: php bin/classmap.php [--check]
 *   --check  exit 1 if src/classmap.php is stale instead of writing it (CI, tests)
 */

declare(strict_types=1);

$root   = dirname( __DIR__ );
$src    = $root . '/src';
$target = $src . '/classmap.php';
$check  = in_array( '--check', $argv, true );

/**
 * @return list<string> fully qualified class, interface, trait, and enum names in a file
 */
function declared_types( string $file ): array {
	$tokens    = token_get_all( (string) file_get_contents( $file ) );
	$namespace = '';
	$types     = [];
	$count     = count( $tokens );

	for ( $i = 0; $i < $count; $i++ ) {
		if ( ! is_array( $tokens[ $i ] ) ) {
			continue;
		}

		if ( T_NAMESPACE === $tokens[ $i ][0] ) {
			$namespace = '';
			for ( $j = $i + 1; $j < $count && ';' !== $tokens[ $j ] && '{' !== $tokens[ $j ]; $j++ ) {
				if ( is_array( $tokens[ $j ] ) && in_array( $tokens[ $j ][0], [ T_NAME_QUALIFIED, T_STRING ], true ) ) {
					$namespace .= $tokens[ $j ][1];
				}
			}
			continue;
		}

		if ( ! in_array( $tokens[ $i ][0], [ T_CLASS, T_INTERFACE, T_TRAIT, T_ENUM ], true ) ) {
			continue;
		}

		// Skip `Foo::class`, `new class`, and `enum` used as an identifier.
		$prev = $i - 1;
		while ( $prev >= 0 && is_array( $tokens[ $prev ] ) && T_WHITESPACE === $tokens[ $prev ][0] ) {
			$prev--;
		}
		if ( $prev >= 0 && is_array( $tokens[ $prev ] ) && in_array( $tokens[ $prev ][0], [ T_DOUBLE_COLON, T_NEW ], true ) ) {
			continue;
		}

		for ( $j = $i + 1; $j < $count; $j++ ) {
			if ( is_array( $tokens[ $j ] ) && T_WHITESPACE === $tokens[ $j ][0] ) {
				continue;
			}
			if ( is_array( $tokens[ $j ] ) && T_STRING === $tokens[ $j ][0] ) {
				$types[] = ltrim( $namespace . '\\' . $tokens[ $j ][1], '\\' );
			}
			break;
		}
	}

	return $types;
}

$map   = [];
$files = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $src, FilesystemIterator::SKIP_DOTS ) );
foreach ( $files as $file ) {
	if ( 'php' !== $file->getExtension() || $file->getPathname() === $target ) {
		continue;
	}
	foreach ( declared_types( $file->getPathname() ) as $type ) {
		$map[ $type ] = substr( $file->getPathname(), strlen( $src ) );
	}
}
ksort( $map );

$lines = [];
foreach ( $map as $type => $path ) {
	$lines[] = sprintf( "\t%s => %s,", var_export( $type, true ), var_export( $path, true ) );
}
$php = "<?php\n// Generated by bin/classmap.php. Do not edit; run `composer classmap`.\n\nreturn [\n"
	. implode( "\n", $lines ) . "\n];\n";

$current = is_file( $target ) ? file_get_contents( $target ) : '';

if ( $check ) {
	if ( $current !== $php ) {
		fwrite( STDERR, "src/classmap.php is stale. Run `composer classmap`.\n" );
		exit( 1 );
	}
	echo "src/classmap.php is current (" . count( $map ) . " types).\n";
	exit( 0 );
}

file_put_contents( $target, $php );
echo "Wrote src/classmap.php (" . count( $map ) . " types).\n";
